"""Taint tracking over an OpenAI-style message list.

Each message gets an effective label:
- user / system / tool messages: the project's baseline label, raised to FLOOR if they
  contain credentials or personal information.
- assistant messages the gateway did not produce: conservatively the join of every label
  before them, since they were generated by a model that saw that whole context.
- assistant messages the gateway produced itself: the label of the context they were
  actually generated from (recorded as provenance). This is what stops one early secret
  from tainting the rest of the session.
"""
import hashlib
import json
from dataclasses import dataclass

from .detect import has_floor
from .labels import Label, join


def message_text(msg: dict) -> str:
    """All text a message carries, including tool-call arguments."""
    parts = []
    content = msg.get("content")
    if isinstance(content, str):
        parts.append(content)
    elif isinstance(content, list):
        parts += [p.get("text", "") for p in content if isinstance(p, dict)]
    for call in msg.get("tool_calls") or []:
        parts.append(json.dumps(call.get("function", {}), ensure_ascii=False, sort_keys=True))
    return "\n".join(parts)


def fingerprint(msg: dict) -> str:
    return hashlib.sha256(message_text(msg).encode("utf-8")).hexdigest()


class Provenance:
    """Labels of assistant messages generated by the gateway, keyed by content fingerprint."""

    def __init__(self) -> None:
        self._labels: dict[str, Label] = {}

    def record(self, msg: dict, label: Label) -> None:
        self._labels[fingerprint(msg)] = label

    def lookup(self, msg: dict) -> Label | None:
        return self._labels.get(fingerprint(msg))


@dataclass
class LabeledMessage:
    msg: dict
    own: Label        # label of the message's own content
    effective: Label  # own label joined with whatever it was derived from


def label_messages(messages: list[dict], baseline: Label, provenance: Provenance,
                   baseline_for=None) -> list[LabeledMessage]:
    """`baseline_for(i, msg)` optionally overrides the project baseline per message (learned rules)."""
    out: list[LabeledMessage] = []
    running = Label.PUBLIC
    for i, msg in enumerate(messages):
        base = baseline_for(i, msg) if baseline_for else baseline
        own = Label.FLOOR if has_floor(message_text(msg)) else base
        if msg.get("role") == "assistant":
            known = provenance.lookup(msg)
            derived = known if known is not None else running
            effective = join(own, derived)
        else:
            effective = own
        out.append(LabeledMessage(msg, own, effective))
        running = join(running, effective)
    return out
