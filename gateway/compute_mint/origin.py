"""Origin dimension: who or what produced a piece of content.

Labels say how confidential content is; origins say where it came from. They are separate
because the constraint is different: Anthropic's and OpenAI's terms forbid using their
models' outputs to train competing models, and Contributor traffic is used by Meta for
training. So output from those models (or from a model we cannot identify) must never be
part of a Contributor request, however public its content is.

Contributor condition: label fits the dial AND origin is not in NON_CONTRIBUTOR.

Origins of messages in an OpenAI-style list:
- user / system / developer messages: USER
- tool messages: TOOL
- assistant messages the gateway generated (found in provenance): META, unless the context
  they were generated from already contained non-contributable origins (see OriginTracker)
- any other assistant message: the model the caller declared (x-cm-client), else UNKNOWN_MODEL
"""
import hashlib
from dataclasses import dataclass, field
from enum import Enum

from .context import Provenance, message_text


class Origin(str, Enum):
    USER = "user"
    TOOL = "tool"
    PUBLIC_SOURCE = "public_source"   # fetched by the gateway from a public URL or public file
    META = "meta"                     # generated by a Meta model through the gateway
    LOCAL_MODEL = "local_model"
    ANTHROPIC = "anthropic"
    OPENAI = "openai"
    UNKNOWN_MODEL = "unknown_model"


# Highest priority first; also the order used to name the origin a reply derives from.
NON_CONTRIBUTOR: tuple[Origin, ...] = (Origin.ANTHROPIC, Origin.OPENAI, Origin.UNKNOWN_MODEL)

# What a caller may declare with x-cm-client. A declaration can only name a non-contributable
# origin, so it can never make foreign content look safer.
CLIENT_VALUES: dict[str, Origin] = {"anthropic": Origin.ANTHROPIC, "openai": Origin.OPENAI,
                                    "unknown": Origin.UNKNOWN_MODEL}


def origin_allows_contributor(origin: Origin) -> bool:
    return origin not in NON_CONTRIBUTOR


def parse_client(value: str | None) -> Origin | None:
    """Value of the x-cm-client header. Raises ValueError for anything but anthropic|openai|unknown."""
    if value is None or value == "":
        return None
    try:
        return CLIENT_VALUES[value.strip().lower()]
    except KeyError:
        raise ValueError(f"x-cm-client must be one of {sorted(CLIENT_VALUES)}") from None


def blocking_origin(origins: list[Origin]) -> Origin | None:
    """The non-contributable origin a reply generated from `origins` derives from, if any."""
    present = set(origins)
    return next((o for o in NON_CONTRIBUTOR if o in present), None)


def _key(msg: dict) -> str:
    return hashlib.sha256(message_text(msg).encode("utf-8")).hexdigest()


def _check_client(client: Origin | None) -> Origin:
    if client is None:
        return Origin.UNKNOWN_MODEL
    if client not in NON_CONTRIBUTOR:
        raise ValueError("a caller can only be declared as anthropic, openai or unknown_model")
    return client


@dataclass
class OriginTracker:
    """Per-session record of gateway replies that derive from non-contributable origins.

    A Meta reply generated on the Standard lane from a context that held Claude or GPT
    output is still derived from that output, so it is not safe to carry into Contributor
    either. This is the origin analogue of the label recorded in Provenance.
    """
    _derived: dict[str, Origin] = field(default_factory=dict)

    def record_reply(self, msg: dict, context_origins: list[Origin]) -> None:
        source = blocking_origin(context_origins)
        if source is not None:
            self._derived[_key(msg)] = source

    def of_messages(self, messages: list[dict], provenance: Provenance,
                    client: Origin | None = None) -> list[Origin]:
        return message_origins(messages, provenance, client, self)


def message_origins(messages: list[dict], provenance: Provenance, client: Origin | None = None,
                    tracker: OriginTracker | None = None) -> list[Origin]:
    out: list[Origin] = []
    for msg in messages:
        role = msg.get("role")
        if role == "assistant":
            if provenance.lookup(msg) is None:
                out.append(_check_client(client))
            else:
                derived = tracker._derived.get(_key(msg)) if tracker else None
                out.append(derived if derived is not None else Origin.META)
        elif role == "tool":
            out.append(Origin.TOOL)
        else:
            out.append(Origin.USER)
    return out
